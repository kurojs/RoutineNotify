export function resolveUiLanguage(uiLanguage: string): UILang {
  if (!ALL_LANGS.includes(uiLanguage as UILang)) {
    const detected = navigator.language.split('-')[0].toLowerCase()
    return (ALL_LANGS as string[]).includes(detected) ? (detected as UILang) : 'en'
  }
  return uiLanguage as UILang
}

export function getTranslation(uiLanguage: string): Translation {
  return translations[resolveUiLanguage(uiLanguage)]
}

export function translate(uiLanguage: string, key: TranslationKey): string {
  return getTranslation(uiLanguage)[key]
}
